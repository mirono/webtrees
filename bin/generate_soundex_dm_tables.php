declare(strict_types=1);

// Generates lib/soundex-dm-tables.js directly from Soundex::TRANSFORM_NAMES
// and Soundex::DM_SOUNDS via reflection, rather than hand-transcribing ~512
// lines of lookup-table data (see docs/php-to-js-migration/task-02-soundex-daitch-mokotoff.md
// "Handling the lookup tables" — this is a stronger guarantee of fidelity
// than diffing a manual transcription: the JS is generated straight from
// the live PHP constant, so there is nothing to transcribe or drop.

require_once __DIR__ . '/../vendor/autoload.php';

use Fisharebest\Webtrees\Soundex;

$reflection = new ReflectionClass(Soundex::class);

$maxchar        = $reflection->getReflectionConstant('MAXCHAR')->getValue();
$transformNames = $reflection->getReflectionConstant('TRANSFORM_NAMES')->getValue();
$dmSounds       = $reflection->getReflectionConstant('DM_SOUNDS')->getValue();

$json_flags = JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE;

$js = <<<'JS'
/**
 * webtrees: online genealogy
 * Copyright (C) 2026 webtrees development team
 * This program is free software: you can redistribute it and/or modify
 * it under the terms of the GNU General Public License as published by
 * the Free Software Foundation, either version 3 of the License, or
 * (at your option) any later version.
 * This program is distributed in the hope that it will be useful,
 * but WITHOUT ANY WARRANTY; without even the implied warranty of
 * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the
 * GNU General Public License for more details.
 * You should have received a copy of the GNU General Public License
 * along with this program. If not, see <https://www.gnu.org/licenses/>.
 */

// GENERATED FILE — do not hand-edit.
// Generated by bin/generate_soundex_dm_tables.php from the live
// Fisharebest\Webtrees\Soundex::TRANSFORM_NAMES / DM_SOUNDS / MAXCHAR
// constants in app/Soundex.php, via PHP reflection (not hand-transcribed —
// see docs/php-to-js-migration/task-02-soundex-daitch-mokotoff.md).
// Regenerate with: php bin/generate_soundex_dm_tables.php

export const MAXCHAR = __MAXCHAR__;

export const TRANSFORM_NAMES = __TRANSFORM_NAMES__;

export const DM_SOUNDS = __DM_SOUNDS__;
JS;

$js = str_replace('__MAXCHAR__', (string) $maxchar, $js);
$js = str_replace('__TRANSFORM_NAMES__', json_encode($transformNames, $json_flags), $js);
$js = str_replace('__DM_SOUNDS__', json_encode($dmSounds, $json_flags), $js);

file_put_contents(__DIR__ . '/../lib/soundex-dm-tables.js', $js);

echo 'Generated lib/soundex-dm-tables.js: ' . count($transformNames) . ' TRANSFORM_NAMES entries, ' . count($dmSounds) . " DM_SOUNDS entries\n";
