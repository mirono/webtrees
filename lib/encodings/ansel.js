  /**
   * Convert a string from ANSEL to UTF-8.
   */
  toUtf8(text) {
    // ANSEL diacritics are prefixes. UTF-8 diacritics are suffixes.
    text = text.replace(/([\xE0-\xFF]+)(.)/g, '$2$1');

    // Simple substitution creates denormalized UTF-8.
    text = super.toUtf8(text);

    // Convert combining diacritics into pre-composed characters.
    return phpStrtr(text, this.constructor.PRECOMPOSED_CHARACTERS);
  }

  /**
   * Convert a string from UTF-8 to ANSEL.
   */
  fromUtf8(text) {
    // Convert pre-composed characters into combining diacritics.
    text = phpStrtr(text, phpArrayFlip(this.constructor.PRECOMPOSED_CHARACTERS));

    // ANSEL supports letters with horns, but not the combining horn.
    text = phpStrtr(text, this.constructor.HORN_CONVERT_STEP_1);

    // Convert characters and combining diacritics separately.
    text = super.fromUtf8(text);

    // ANSEL supports two letters with horns, but not the combining horn.
    text = phpStrtr(text, this.constructor.HORN_CONVERT_STEP_2);

    // ANSEL diacritics are prefixes. UTF-8 diacritics are suffixes.
    text = text.replace(/([^\xE0-\xFF])([\xE0-\xFF]+)/g, '$2$1');

    return text;
  }
