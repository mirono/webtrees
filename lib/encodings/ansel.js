// ANSEL diacritics are prefix bytes (0xE0-0xFF); the base character they
// modify follows. Unicode combining diacritics are suffix code points; the
// base character precedes them. So converting between the two encodings
// requires reordering, plus (on the way to UTF-8) folding decomposed
// base+combining sequences into precomposed single characters where one
// exists, and (on the way back) the reverse plus a workaround for the two
// ANSEL "horn" letters (o/u with horn) which ANSEL represents as their own
// bytes but Unicode only has as a combining sequence.

